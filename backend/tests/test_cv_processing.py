def _upload(api, name: str, data: bytes, mime: str = "application/octet-stream"):
    return api.client.post(
        "/api/v1/cvs/upload", files={"file": (name, data, mime)}, headers={"X-CSRF-Token": api.client.cookies.get("tf_csrf")}
    )


